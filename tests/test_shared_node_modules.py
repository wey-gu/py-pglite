class TestPackageJsonContents:
    """The npm package pins track the latest PGlite releases."""

    def test_latest_pglite_packages(self):
        manager = PGliteManager(PGliteConfig())
        dependencies = manager._package_json_content()["dependencies"]
        assert dependencies == {
            "@electric-sql/pglite": "^0.5.8",
            "@electric-sql/pglite-socket": "^0.2.11",
        }

    def test_pgvector_package_added_when_enabled(self):
        manager = PGliteManager(PGliteConfig(extensions=["pgvector"]))
        dependencies = manager._package_json_content()["dependencies"]
        assert dependencies["@electric-sql/pglite-pgvector"] == "^0.0.9"
        assert dependencies["@electric-sql/pglite"] == "^0.5.8"

    def test_pgvector_package_not_added_by_other_extensions(self):
        manager = PGliteManager(PGliteConfig(extensions=["pg_trgm"]))
        dependencies = manager._package_json_content()["dependencies"]
        assert "@electric-sql/pglite-pgvector" not in dependencies


class TestStartupProbe:
    """The readiness probe performs a real PostgreSQL startup handshake."""

    @staticmethod
    def _recv_exact(sock, count):
        data = b""
        while len(data) < count:
            chunk = sock.recv(count - len(data))
            if not chunk:
                return None
            data += chunk
        return data

    def test_probe_returns_true_after_ready_for_query(self):
        client, server = socket.socketpair()

        def serve():
            length = struct.unpack("!i", self._recv_exact(server, 4))[0]
            self._recv_exact(server, length - 4)
            server.sendall(b"R" + struct.pack("!ii", 8, 0))
            server.sendall(b"Z" + struct.pack("!i", 5) + b"I")
            assert self._recv_exact(server, 5) == b"X\x00\x00\x00\x04"

        thread = threading.Thread(target=serve)
        thread.start()
        try:
            assert _postgres_startup_probe(client) is True
        finally:
            thread.join(timeout=5)
            client.close()
            server.close()

    def test_probe_returns_false_when_server_closes(self):
        client, server = socket.socketpair()
        server.close()
        try:
            assert _postgres_startup_probe(client) is False
        finally:
            client.close()


