class TestSharedNodeModulesInstall:
    """Install behaviour with node_modules_dir configured."""

    def test_installs_once_and_links_work_dir(self, tmp_path):
        work_dir = tmp_path / "work"
        shared_dir = tmp_path / "shared"
        config = PGliteConfig(work_dir=work_dir, node_modules_dir=shared_dir)
        manager = PGliteManager(config)
        calls = []

        with patch(
            "py_pglite.manager.subprocess.run", side_effect=_make_npm_run(calls)
        ):
            manager._install_dependencies(work_dir)
            # A second worker must reuse the existing install.
            manager._install_dependencies(work_dir)

        assert calls == [(["npm", "install"], shared_dir)]
        link = work_dir / "node_modules"
        assert link.is_symlink()
        assert link.resolve() == (shared_dir / "node_modules").resolve()
        assert find_pglite_modules(work_dir).resolve() == link.resolve()
        assert (shared_dir / "package.json").exists()

    def test_reuses_matching_shared_install(self, tmp_path):
        work_dir = tmp_path / "work"
        shared_dir = tmp_path / "shared"
        config = PGliteConfig(work_dir=work_dir, node_modules_dir=shared_dir)
        manager = PGliteManager(config)
        shared_dir.mkdir(parents=True)
        (shared_dir / "node_modules/@electric-sql/pglite").mkdir(parents=True)
        (shared_dir / "package.json").write_text(
            json.dumps(manager._package_json_content())
        )
        calls = []

        with patch(
            "py_pglite.manager.subprocess.run", side_effect=_make_npm_run(calls)
        ):
            manager._install_dependencies(work_dir)

        assert calls == []
        assert (work_dir / "node_modules").is_symlink()

    def test_reinstalls_when_shared_package_json_changes(self, tmp_path):
        work_dir = tmp_path / "work"
        shared_dir = tmp_path / "shared"
        config = PGliteConfig(work_dir=work_dir, node_modules_dir=shared_dir)
        manager = PGliteManager(config)
        shared_dir.mkdir(parents=True)
        node_modules = shared_dir / "node_modules"
        (node_modules / "@electric-sql/pglite").mkdir(parents=True)
        (node_modules / "stale-marker").write_text("old")
        (shared_dir / "package.json").write_text(json.dumps({"dependencies": {}}))
        calls = []

        with patch(
            "py_pglite.manager.subprocess.run", side_effect=_make_npm_run(calls)
        ):
            manager._install_dependencies(work_dir)

        assert calls == [(["npm", "install"], shared_dir)]
        assert not (node_modules / "stale-marker").exists()
        assert (
            json.loads((shared_dir / "package.json").read_text())
            == manager._package_json_content()
        )

    def test_links_over_plain_work_dir_node_modules(self, tmp_path):
        work_dir = tmp_path / "work"
        shared_dir = tmp_path / "shared"
        config = PGliteConfig(work_dir=work_dir, node_modules_dir=shared_dir)
        manager = PGliteManager(config)
        # Simulate a work_dir from a previous per-work-dir install.
        old_modules = work_dir / "node_modules"
        (old_modules / "@electric-sql/pglite").mkdir(parents=True)
        (shared_dir / "node_modules/@electric-sql/pglite").mkdir(parents=True)
        (shared_dir / "package.json").write_text(
            json.dumps(manager._package_json_content())
        )
        calls = []

        with patch(
            "py_pglite.manager.subprocess.run", side_effect=_make_npm_run(calls)
        ):
            manager._install_dependencies(work_dir)

        assert calls == []
        assert (work_dir / "node_modules").is_symlink()
        assert (work_dir / "node_modules").resolve() == (
            shared_dir / "node_modules"
        ).resolve()

    def test_auto_install_disabled_skips_shared_install(self, tmp_path):
        work_dir = tmp_path / "work"
        config = PGliteConfig(
            work_dir=work_dir,
            node_modules_dir=tmp_path / "shared",
            auto_install_deps=False,
        )
        manager = PGliteManager(config)
        calls = []

        with patch(
            "py_pglite.manager.subprocess.run", side_effect=_make_npm_run(calls)
        ):
            manager._install_dependencies(work_dir)

        assert calls == []
        assert not (work_dir / "node_modules").exists()

    def test_check_disabled_still_links_existing_shared_install(self, tmp_path):
        work_dir = tmp_path / "work"
        shared_dir = tmp_path / "shared"
        config = PGliteConfig(
            work_dir=work_dir,
            node_modules_dir=shared_dir,
            node_modules_check=False,
        )
        manager = PGliteManager(config)
        (shared_dir / "node_modules/@electric-sql/pglite").mkdir(parents=True)
        calls = []

        with patch(
            "py_pglite.manager.subprocess.run", side_effect=_make_npm_run(calls)
        ):
            manager._install_dependencies(work_dir)

        assert calls == []
        assert (work_dir / "node_modules").is_symlink()

    def test_per_work_dir_install_without_shared_dir(self, tmp_path):
        work_dir = tmp_path / "work"
        config = PGliteConfig(work_dir=work_dir)
        manager = PGliteManager(config)
        calls = []

        with patch(
            "py_pglite.manager.subprocess.run", side_effect=_make_npm_run(calls)
        ):
            manager._install_dependencies(work_dir)
            # The fake install created node_modules, so it is not repeated.
            manager._install_dependencies(work_dir)

        assert calls == [(["npm", "install"], work_dir)]

