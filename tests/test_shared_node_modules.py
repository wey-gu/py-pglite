def _make_npm_run(calls):
    """Return a subprocess.run replacement that records calls and fakes npm."""

    def fake_run(args, **kwargs):
        cwd = Path(kwargs["cwd"])
        calls.append((args, cwd))
        (cwd / "node_modules/@electric-sql/pglite").mkdir(parents=True, exist_ok=True)
        return Mock(stdout="installed")

    return fake_run


